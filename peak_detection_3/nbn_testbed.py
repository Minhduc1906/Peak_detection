def zone_header ():
	serial = time.strftime ('%Y%m%d01')
	return (
		';\n'
		'; Auto-generated by nbn_testbed.py\n'
		';\n'
		'$TTL\t604800\n'
		'@\tIN\tSOA\tlocalhost. root.localhost. (\n'
		f'\t\t     {serial}\t\t; Serial\n'
		'\t\t\t 604800\t\t; Refresh\n'
		'\t\t\t  86400\t\t; Retry\n'
		'\t\t\t2419200\t\t; Expire\n'
		'\t\t\t 604800 )\t; Negative Cache TTL\n'
		';\n'
		'@\tIN\tNS\tlocalhost.\n\n'
	)

def write_zone_file (path, content):
	with open (path, 'w', encoding = 'utf-8') as handle:
		handle.write (content)


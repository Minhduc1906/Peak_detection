def build_mgmt_plan (households, clients_per_household, server_count):
	total_clients = households * clients_per_household
	plan = {
		'dns': 254,
		'r2': 2,
		'r3': 3,
		's2': 12,
		's3': 13,
		's4': 14,
		'servers': {},
		'household_switches': {},
		'household_routers': {},
		'clients': {},
	}

	next_octet = 20
	for key, count in [
		('servers', server_count),
		('household_switches', households),
		('household_routers', households),
		('clients', total_clients),
	]:
		last_octet = next_octet + count - 1
		if last_octet >= plan['dns']:
			raise ValueError ('Management subnet exhausted; reduce nodes or expand addressing plan')

		for index in range (1, count + 1):
			plan[key][index] = next_octet + index - 1

		next_octet = last_octet + 10

	return plan

